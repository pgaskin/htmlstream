//go:build ignore

// Command encoding_generate writes encoding_table.go from the encoding
// labels of the WHATWG Encoding Standard. The list is fetched to
// encodings.json if it doesn't exist, or if -refetch is set.
//
// Run it with go generate in this directory.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
)

const encodingsURL = "https://encoding.spec.whatwg.org/encodings.json"

func main() {
	refetch := flag.Bool("refetch", false, "fetch encodings.json even if it exists")
	flag.Parse()

	buf, err := os.ReadFile("encodings.json")
	if err != nil || *refetch {
		if err != nil && !os.IsNotExist(err) {
			log.Fatal(err)
		}
		if buf, err = fetch(encodingsURL); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile("encodings.json", buf, 0o644); err != nil {
			log.Fatal(err)
		}
	}

	var groups []struct {
		Encodings []struct {
			Name   string   `json:"name"`
			Labels []string `json:"labels"`
		} `json:"encodings"`
	}
	if err := json.Unmarshal(buf, &groups); err != nil {
		log.Fatal(err)
	}
	labels := map[string]string{}
	for _, g := range groups {
		for _, e := range g.Encodings {
			for _, l := range e.Labels {
				if _, ok := labels[l]; ok {
					log.Fatalf("duplicate label %q", l)
				}
				labels[l] = e.Name
			}
		}
	}
	if len(labels) == 0 {
		log.Fatal("no labels")
	}
	keys := make([]string, 0, len(labels))
	for l := range labels {
		keys = append(keys, l)
	}
	slices.Sort(keys)

	var b bytes.Buffer
	b.WriteString("// Code generated by encoding_generate.go; DO NOT EDIT.\n\npackage internal\n\n")
	b.WriteString("// encodingLabels maps the encoding labels of the Encoding Standard to\n// the names of their encodings.\n")
	b.WriteString("var encodingLabels = map[string]string{\n")
	for _, l := range keys {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(l), strconv.Quote(labels[l]))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("encoding_table.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
