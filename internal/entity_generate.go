//go:build ignore

// Command entity_generate writes entity_table.go from the WHATWG named
// character reference list. The list is fetched to entity.json if it doesn't
// exist, or if -refetch is set.
//
// Run it with go generate in this directory.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
)

const entitiesURL = "https://html.spec.whatwg.org/entities.json"

func main() {
	refetch := flag.Bool("refetch", false, "fetch entity.json even if it exists")
	flag.Parse()

	buf, err := os.ReadFile("entity.json")
	if err != nil || *refetch {
		if err != nil && !os.IsNotExist(err) {
			log.Fatal(err)
		}
		if buf, err = fetch(entitiesURL); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile("entity.json", buf, 0o644); err != nil {
			log.Fatal(err)
		}
	}

	var raw map[string]struct {
		Codepoints []rune `json:"codepoints"`
		Characters string `json:"characters"`
	}
	if err := json.Unmarshal(buf, &raw); err != nil {
		log.Fatal(err)
	}

	type entity struct {
		name, value string
	}
	var ents []entity
	var maxLen, maxLegacyLen, maxValue int
	for k, v := range raw {
		name, ok := strings.CutPrefix(k, "&")
		if !ok {
			log.Fatalf("entity %q does not start with &", k)
		}
		if string(v.Codepoints) != v.Characters {
			log.Fatalf("entity %q: codepoints and characters differ", k)
		}
		for _, c := range strings.TrimSuffix(name, ";") {
			if !('a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || '0' <= c && c <= '9') {
				log.Fatalf("entity %q: unexpected character %q", k, c)
			}
		}
		maxLen = max(maxLen, len(name))
		if !strings.HasSuffix(name, ";") {
			maxLegacyLen = max(maxLegacyLen, len(name))
			if _, ok := raw[k+";"]; !ok {
				log.Fatalf("legacy entity %q has no semicolon form", k)
			}
		}
		maxValue = max(maxValue, len(v.Characters))
		ents = append(ents, entity{name, v.Characters})
	}
	slices.SortFunc(ents, func(a, b entity) int {
		return strings.Compare(a.name, b.name)
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by entity_generate.go from entity.json; DO NOT EDIT.\n\n")
	b.WriteString("package internal\n\n")
	fmt.Fprintf(&b, "const (\n")
	fmt.Fprintf(&b, "\tEntityMaxName = %d // longest name including ';'\n", maxLen)
	fmt.Fprintf(&b, "\tEntityMaxLegacy = %d // longest name without ';'\n", maxLegacyLen)
	fmt.Fprintf(&b, "\tEntityMaxValue = %d // longest UTF-8 value\n", maxValue)
	fmt.Fprintf(&b, ")\n\n")
	b.WriteString("// entities contains the HTML5 named character references sorted by name.\n")
	b.WriteString("// Names exclude the leading '&'. Legacy names, which may be used without\n")
	b.WriteString("// a terminating ';', are also present with it.\n")
	b.WriteString("var entities = [...]struct{ name, value string }{\n")
	for _, e := range ents {
		fmt.Fprintf(&b, "\t{%q, %s},\n", e.name, strconv.QuoteToASCII(e.value))
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("entity_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
